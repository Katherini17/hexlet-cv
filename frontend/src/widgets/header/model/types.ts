/**
 * Интерфейс, описывающий структуру навигационной ссылки в шапке сайта.
 * Используется для типизации конфигурационных списков меню и элементов навигации.
 */
export interface HeaderLink {
  /** Текст ссылки, который будет отображаться пользователю в интерфейсе. */
  label: string
  /** URL-путь (маршрут) или хэш-якорь (например, '/#features') для перехода. */
  link: string
}
